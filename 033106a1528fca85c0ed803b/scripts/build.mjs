import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
const commit=process.argv[2];
if(!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(commit||'')) throw Error('需要完整源码提交号');
const source=JSON.parse(await readFile('source.json','utf8'));
await mkdir('dist/assets',{recursive:true});
await copyFile('src/app.js','dist/assets/app.js');
await copyFile('src/style.css','dist/assets/app.css');
await copyFile('public/icon.png','dist/icon.png');
const js=await readFile('dist/assets/app.js','utf8');
await writeFile('dist/assets/app.js',`const link=document.createElement('link');link.rel='stylesheet';link.href=new URL('./app.css',import.meta.url);document.head.appendChild(link);\n`+js);
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',git_instance_id:source.git_instance_id}));
