import {readFile, mkdir, rm, writeFile, copyFile} from 'node:fs/promises';
const commit = process.argv[2];
if (!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(commit || '')) throw new Error('需要完整源码提交号');
const source = JSON.parse(await readFile('source.json','utf8'));
if (process.env.TIANA_TEMPLATE_BUILD !== '1' && (!/^[A-Za-z0-9_-]{1,128}$/.test(source.git_instance_id || '') || source.git_instance_id.startsWith('__TIANA_'))) throw new Error('请填写 Git 实例 ID');
const html = await readFile('client/index.html','utf8');
const body = html.match(/<svg class="icon-sprite"[\s\S]*?<\/main>/)?.[0];
if (!body) throw new Error('找不到界面');
const css = await readFile('client/styles.css','utf8');
const scripts = await Promise.all(['time.js','cities.js','app.js'].map(x=>readFile('client/'+x,'utf8')));
const setup = `document.title='A/时差保安';\nconst style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);\ndocument.getElementById('app').innerHTML=${JSON.stringify(body)};\n`;
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await writeFile('dist/assets/app.js', setup + scripts.join('\n;\n'));
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
