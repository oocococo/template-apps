import {readFile, mkdir, writeFile, copyFile, rm} from 'node:fs/promises';
const commit=process.argv[2]; if(!/^[a-f0-9]{40,64}$/.test(commit||'')) throw Error('需要完整提交号');
const source=JSON.parse(await readFile('source.json','utf8'));
if(process.env.TIANA_TEMPLATE_BUILD!=='1' && source.git_instance_id.startsWith('__TIANA_')) throw Error('需要 Git 实例 ID');
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
const body=await readFile('src/body.html','utf8'); const css=await readFile('src/main.css','utf8');
let js=`document.getElementById('app').innerHTML=${JSON.stringify(body)};\nconst style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);\n`;
for(const file of ['data-rhyme.js','data-lexicon.js','core.js','app.js']) js+=await readFile('src/'+file,'utf8')+'\n';
await writeFile('dist/assets/app.js',js); await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
