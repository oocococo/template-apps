const F = (s, f) => s.flags.includes(f)
const hasChild = s => F(s, 'has_prince') || F(s, 'has_princess') || F(s, 'two_children')

function E(id, stage, year, title, scene, opts, extra) {
  const ev = {
    id, stage, year, title, scene,
    options: opts.map(o => {
      const x = { text: o[0] }
      if (o[1]) x.effects = o[1]
      if (o[2]) x.result = o[2]
      if (o[3]) Object.assign(x, o[3])
      return x
    })
  }
  return Object.assign(ev, extra || {})
}

function A(id, stage, year, title, scene, resolve, extra) {
  return Object.assign({ id, stage, year, title, scene, auto: true, resolve }, extra || {})
}

/* 生产结算：皇子 / 公主 / 难产。怀孕可能发生在任何阶段，
 * 所以每个阶段都放一条同样的"生"事件，谁先 cond 成立谁生效。 */
function birthResolve(s) {
  s.flags.push('preg_done')
  const r = Math.random()
  if (s.health < 38 || r < 0.08) {
    s.flags.push('died_in_childbirth')
    return { text: '血止不住。你听见婴儿哭了一声，很响。你想看一眼，眼皮已经抬不起来了。最后你想的是：他活着，就好。', tone: 'bad' }
  }
  if (r < 0.6) {
    s.flags.push('has_prince')
    s.rank = Math.min(8, s.rank + 1)
    return { text: '是个皇子。稳婆抱出来时，外面一片道喜声。你躺在床上，看着那个皱巴巴的小东西，忽然哭了。这宫里，你终于有了一样真正属于自己的。', tone: 'good', effects: { fame: 10, favor: 8, peace: 4 } }
  }
  s.flags.push('has_princess')
  return { text: '是个公主。有人道喜，声音比刚才稀疏些。你把孩子抱在怀里，看她的小手抓着你的衣襟。你想：公主也好，公主将来不必困在这里。', tone: 'neutral', effects: { fame: 5, favor: 4, peace: 6 } }
}

function birthEvent(id, stage, year) {
  return A(id, stage, year, '生产', '阵痛从半夜开始，一直疼到第二天午后。稳婆进进出出，锦儿握着你的手，手心里全是汗。你听见外面有人在念经，也听见有人在低声说话。',
    birthResolve, { always: true, critical: true, cond: s => F(s, 'preg') && !F(s, 'preg_done'), order: 4 })
}

/* 把人送进冷宫：数值一次性打到底 */
function toColdPalace(s) {
  if (!s.flags.includes('cold_palace')) s.flags.push('cold_palace')
  s.rank = 0
  s.favor = 2
  s.fame = Math.max(0, s.fame - 30)
  s.power = Math.max(0, s.power - 30)
  s.peace = Math.max(0, s.peace - 20)
}

