  function monthIn(stage, i, n) {
    const r = SPAN[stage] || [30, 60]
    return r[0] + Math.round((i / Math.max(1, n - 1)) * (r[1] - r[0]))
  }

  function cartesian(vars, keys, out, cur, i) {
    if (out.length >= 300) return
    if (i >= keys.length) { out.push(Object.assign({}, cur)); return }
    const k = keys[i]
    for (let j = 0; j < vars[k].length; j++) {
      cur[k] = vars[k][j]
      cartesian(vars, keys, out, cur, i + 1)
      if (out.length >= 300) return
    }
  }

  function expand(fam) {
    const n = fam.n || 12
    const keys = Object.keys(fam.vars)
    const all = []
    cartesian(fam.vars, keys, all, {}, 0)
    for (let i = all.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1))
      const t = all[i]; all[i] = all[j]; all[j] = t
    }
    const count = Math.min(n, all.length)
    for (let i = 0; i < count; i++) {
      const v = all[i]
      const t = fam.build(v, i)
      const stage = (fam.stages || [3])[i % (fam.stages || [3]).length]
      OUT.push({
        id: fam.id + '_' + (i + 1),
        family: fam.id,
        stage: stage,
        month: fam.monthAt ? fam.monthAt(i, count, stage) : monthIn(stage, i, count),
        title: t.title,
        scene: t.scene,
        cond: mergeCond(fam.cond, t.cond),
        chance: fam.chance,
        optPanels: t.optPanels || fam.optPanels || null,
        options: t.options
      })
    }
  }

  function mergeCond(a, b) {
    if (!a) return b || null
    if (!b) return a
    return s => {
      try { return !!a(s) && !!b(s) } catch (e) { return false }
    }
  }

