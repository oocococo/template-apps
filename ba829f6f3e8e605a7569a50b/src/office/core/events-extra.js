  function add(id, stage, month, title, scene, opts, extra) {
    const options = []
    for (let i = 0; i < opts.length; i++) {
      const o = opts[i]
      if (!o) continue
      const it = { text: o[0], effects: o[1] || {} }
      if (o[2]) it.result = o[2]
      if (o[3]) for (const k in o[3]) it[k] = o[3][k]
      options.push(it)
    }
    const ev = { id: id, stage: stage, month: month, title, scene, options, always: true }
    if (extra) for (const k in extra) ev[k] = extra[k]
    OUT.push(ev)
  }

