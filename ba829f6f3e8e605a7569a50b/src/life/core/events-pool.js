  /* ------------------------- 展开器 ------------------------- */

  function cartesian(vars, keys, out, cur, i) {
    if (out.length >= 400) return
    if (i >= keys.length) { out.push(Object.assign({}, cur)); return }
    const k = keys[i]
    for (let j = 0; j < vars[k].length; j++) {
      cur[k] = vars[k][j]
      cartesian(vars, keys, out, cur, i + 1)
      if (out.length >= 400) return
    }
  }

  /**
   * 把一个族展开成 n 条事件
   *
   * 组合必须先洗牌再取，不能按笛卡尔积顺序取前 n 个：
   * 笛卡尔积是"最后一个变量变化最快"，顺序取会让前十几个组合的第一个变量全一样
   * （`p_child_unfair` 就出现过 50 条里 13 条都是"花瓶碎了"）。
   * 另外 n 不能超过组合总数，否则同一个组合会被复制好几遍。
   */
  function expand(fam, n) {
    const keys = Object.keys(fam.vars)
    const all = []
    cartesian(fam.vars, keys, all, {}, 0)

    for (let i = all.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1))
      const t = all[i]; all[i] = all[j]; all[j] = t
    }

    const count = Math.min(n, all.length)
    const out = []
    for (let i = 0; i < count; i++) {
      const v = all[i]
      const t = fam.build(v, i)
      out.push({
        id: fam.id + '_' + (i + 1),
        family: fam.id,
        stage: fam.stages[i % fam.stages.length],
        age: fam.ageAt ? fam.ageAt(i, count) : 30,
        title: t.title,
        scene: t.scene,
        // build 可以按这条组合的措辞追加条件（例：只有"你婆婆"才要求女性），与族条件取交集
        cond: mergeCond(fam.cond, t.cond),
        chance: fam.chance,
        order: fam.order,
        // build 也可以给这条组合定制讲法（函数形式，运行时按状态落定）
        sceneAlt: t.sceneAlt || null,
        // 选项面板的多套说法：一个族的几十条共用同一组选项，不给变体的话
        // 玩家第二局就会把三个按钮背下来。engine 按哈希挑一套。
        optPanels: t.optPanels || fam.optPanels || null,
        options: t.options
      })
    }
    return out
  }

  function mergeCond(a, b) {
    if (!a) return b || null
    if (!b) return a
    return s => {
      try { return !!a(s) && !!b(s) } catch (e) { return false }
    }
  }

