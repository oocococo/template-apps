import {readFile,mkdir,rm,writeFile,copyFile} from 'node:fs/promises';
const commit=process.argv[2];
if(!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(commit||'')) throw Error('需要完整源码提交号');
const source=JSON.parse(await readFile('source.json','utf8'));
if(process.env.TIANA_TEMPLATE_BUILD!=='1' && (!/^[A-Za-z0-9_-]{1,128}$/.test(source.git_instance_id||'')||source.git_instance_id.startsWith('__TIANA_'))) throw Error('请填写 Git 实例 ID');
const html=await readFile('client/index.html','utf8');
const css=html.match(/<style[^>]*>([\s\S]*?)<\/style>/)[1]+'\n#app{display:contents} body{grid-template-columns:minmax(0,1fr);width:100vw} .titlebar{min-width:0} .tb-title{min-width:0}';
const body=html.match(/<body[^>]*>([\s\S]*?)<script[^>]*>/)[1];
const script=html.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1];
await rm('dist',{recursive:true,force:true});await mkdir('dist/assets',{recursive:true});
await writeFile('dist/assets/app.js',`document.title='报错诊所 ErrorClinic';\nconst style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);\ndocument.getElementById('app').innerHTML=${JSON.stringify(body)};\n`+script);
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
