import {readFile,writeFile,mkdir,copyFile,rm} from 'node:fs/promises';
const commit=process.argv[2];
if(!/^[0-9a-f]{40}$/.test(commit||'')) throw Error('需要完整源码提交号');
const source=JSON.parse(await readFile('source.json','utf8'));
if(!process.env.TIANA_TEMPLATE_BUILD && Object.values(source).some(v=>v.startsWith('__TIANA_'))) throw Error('请填写 Git 实例绑定');
const css=await readFile('src/style.css','utf8'),html=await readFile('src/layout.html','utf8'),js=await readFile('src/circuit.js','utf8');
await rm('dist',{recursive:true,force:true});await mkdir('dist/assets',{recursive:true});
await writeFile('dist/assets/app.js',`document.title="电学实验室";const style=document.createElement("style");style.textContent=${JSON.stringify(css)};document.head.append(style);document.getElementById("app").innerHTML=${JSON.stringify(html)};\n${js}`);
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
