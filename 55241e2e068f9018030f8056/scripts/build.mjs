import {readFile, mkdir, rm, writeFile, copyFile} from 'node:fs/promises';
const commit=process.argv[2];
if (!/^[0-9a-f]{40,64}$/.test(commit||'')) throw new Error('需要完整源码提交号');
const source=JSON.parse(await readFile('source.json','utf8'));
if(process.env.TIANA_TEMPLATE_BUILD!=='1' && (!source.git_instance_id || source.git_instance_id.startsWith('__TIANA_'))) throw new Error('填写 Git 实例 ID');
const body=await readFile('src/body.html','utf8');
const css=await readFile('src/style.css','utf8');
const parts=await Promise.all(['core/skills.js','core/rules.js','core/ai.js','core/render.js','main.js'].map(f=>readFile('src/'+f,'utf8')));
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await writeFile('dist/assets/app.js',`document.getElementById('app').innerHTML=${JSON.stringify(body)};\nconst style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);\n`+parts.join('\n;\n'));
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
