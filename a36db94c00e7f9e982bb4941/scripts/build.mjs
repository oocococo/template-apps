import {readFile,writeFile,mkdir,rm,copyFile} from 'node:fs/promises';
import {build} from 'esbuild';
const source=JSON.parse(await readFile('source.json','utf8'));
const html=await readFile('client/index.html','utf8');
const css=html.match(/<style>([\s\S]*?)<\/style>/)[1];
const body=html.match(/<body>([\s\S]*?)<script>/)[1];
const js=html.match(/<script>([\s\S]*?)<\/script>/)[1];
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await build({entryPoints:['client/store.js'],bundle:true,format:'iife',outfile:'dist/assets/store.js'});
const store=await readFile('dist/assets/store.js','utf8');
await rm('dist/assets/store.js');
await writeFile('dist/assets/app.js',store+'\n'+`document.title='改需求逃生战';\nconst style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);document.body.innerHTML=${JSON.stringify(body)};\n`+js);
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source}));
