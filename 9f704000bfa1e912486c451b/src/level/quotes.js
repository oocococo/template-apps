// 自检辅助（复用）：长度 365、每条 <=40、非空、无首尾空白、无换行、仅可打印 ASCII(32-126)。
// 真实 365 条同样必须满足这些约束（TextGeometry + helvetiker 字体要求纯基础拉丁字符）。
export function _validateQuotes() {
  if (QUOTES.length !== 365) throw new Error(`QUOTES length=${QUOTES.length}, expected 365`);
  const PRINTABLE = /^[\u0020-\u007E]+$/;
  for (let i = 0; i < QUOTES.length; i++) {
    const q = QUOTES[i];
    if (typeof q !== 'string' || q.length === 0) throw new Error(`QUOTES[${i}] empty`);
    if (q.length > 40) throw new Error(`QUOTES[${i}] too long (${q.length}): "${q}"`);
    if (q !== q.trim()) throw new Error(`QUOTES[${i}] has surrounding whitespace: "${q}"`);
    if (/[\r\n]/.test(q)) throw new Error(`QUOTES[${i}] has newline: "${q}"`);
    if (!PRINTABLE.test(q)) throw new Error(`QUOTES[${i}] has non-printable-ASCII: "${q}"`);
  }
  return true;
}
