import { build } from 'vite';
import { readFile, stat } from 'node:fs/promises';
const commit = process.argv[2];
if (!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(commit ?? '')) throw new Error('构建需要完整源码提交号。');
const source = JSON.parse(await readFile('source.json', 'utf8'));
if (process.env.TIANA_TEMPLATE_BUILD !== '1' && Object.values(source).some((id) => typeof id !== 'string' || id.startsWith('__TIANA_'))) throw new Error('请先填写实际资源绑定。');
await build();
await stat('dist/assets/app.js');
await stat('dist/assets/app.css');
await stat('dist/icon.png');
console.log('TIANA_PROJECT_PARAMS ' + JSON.stringify({ entry:'assets/app.js', database_instance_id:source.database_instance_id, git_instance_id:source.git_instance_id, source_commit:commit }));
