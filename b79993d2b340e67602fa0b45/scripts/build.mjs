import {readFile, mkdir, writeFile, copyFile} from 'node:fs/promises';
const html = await readFile('app.html','utf8');
const css = html.match(/<style[^>]*>([\s\S]*?)<\/style>/)[1];
const body = html.match(/<body[^>]*>([\s\S]*?)<script[^>]*>/)[1];
const js = html.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1];
await mkdir('dist/assets',{recursive:true});
await writeFile('dist/assets/app.js', `const style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.append(style);document.getElementById('app').innerHTML=${JSON.stringify(body)};\n${js}`);
await copyFile('public/icon.png','dist/icon.png');
const source=JSON.parse(await readFile('source.json','utf8'));
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',git_instance_id:source.git_instance_id}));
