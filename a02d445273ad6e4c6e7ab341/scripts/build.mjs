import {readFile, writeFile, mkdir, copyFile, rm} from 'node:fs/promises';
import {build} from 'esbuild';
const html=await readFile('app.html','utf8');
const style=html.match(/<style>([\s\S]*?)<\/style>/)[1];
const body=html.match(/<body>([\s\S]*?)<script>/)[1];
const js=html.match(/<script>([\s\S]*?)<\/script>/)[1];
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await build({stdin:{contents:`import * as db from './db.js';\ndocument.title="码力日志";\nconst style=document.createElement('style');style.textContent=${JSON.stringify(style)};document.head.appendChild(style);\ndocument.getElementById('app').innerHTML=${JSON.stringify(body)};\n${js}`,resolveDir:process.cwd(),sourcefile:'entry.js'},bundle:true,format:'iife',platform:'browser',outfile:'dist/assets/app.js'});
await copyFile('public/icon.png','dist/icon.png');
const source=JSON.parse(await readFile('source.json','utf8'));
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',git_instance_id:source.git_instance_id,database_instance_id:source.database_instance_id}));
