/**
 * 把页面需要的诊断结果一次性算好。
 * @param arg { subject, grade, subjectName, gradeName, paper, marks, probeMarks, probeCards, rank }
 */
function analyze(arg) {
  const subject = arg.subject;
  const grade = Number(arg.grade) || 1;
  const paper = arg.paper || [];
  const marks = arg.marks || [];

  const base = scoreBase(paper, marks, subject);
  const plan = probePlan(base);
  const probeCards = arg.probeCards || [];
  const probeMarks = arg.probeMarks || [];

  // 追脉成绩按维度归并（只算真答过的题，跳过追脉时 probeMarks 为空）
  const groups = [];
  const byDim = {};
  const answered = Math.min(probeCards.length, probeMarks.length);
  for (let i = 0; i < answered; i++) {
    const d = probeCards[i].d;
    if (!byDim[d]) {
      byDim[d] = { k: d, right: 0, total: 0, idx: [] };
      groups.push(byDim[d]);
    }
    byDim[d].total += 1;
    byDim[d].idx.push(i);
    if (probeMarks[i]) byDim[d].right += 1;
  }

  const fused = fuse(base, groups);

  // 补维度名 + 提示
  for (let i = 0; i < fused.length; i++) {
    const d = fused[i];
    d.name = dimsUtil.labelOf(subject, grade, d.k);
    const raw = dimsUtil.dimOf(subject, d.k);
    d.hint = raw ? raw.hint : '';
  }

  let right = 0;
  let total = 0;
  for (let i = 0; i < fused.length; i++) {
    right += fused[i].right;
    total += fused[i].total;
  }
  const mastery = total ? Math.round((right / total) * 100) : 0;

  const sorted = fused.slice().sort(function (a, b) { return a.rate - b.rate; });
  const firstWeak = sorted.length && sorted[0].rate < 0.999 ? sorted[0] : null;

  let gaps = 0;
  let slips = 0;
  for (let i = 0; i < fused.length; i++) {
    if (fused[i].verdict.key === 'gap') gaps++;
    if (fused[i].verdict.key === 'slip') slips++;
  }

  const probeGroups = [];
  for (let i = 0; i < groups.length; i++) {
    const g = groups[i];
    const merged = fused.filter(function (x) { return x.k === g.k; })[0];
    probeGroups.push({
      k: g.k,
      name: dimsUtil.labelOf(subject, grade, g.k),
      right: g.right,
      total: g.total,
      pct: g.total ? Math.round((g.right / g.total) * 100) : 0,
      verdict: merged ? merged.verdict : null,
      jumped: merged ? merged.pct : 0
    });
  }

  const trail = buildPlan(fused, {
    subject: subject,
    grade: grade,
    subjectName: arg.subjectName || '',
    gradeName: arg.gradeName || ''
  });

  const words = buildWords({
    rank: arg.rank,
    mastery: mastery,
    first: firstWeak,
    firstName: firstWeak ? dimsUtil.labelOf(subject, grade, firstWeak.k) : '',
    gaps: gaps,
    slips: slips
  });

  // 雷达图用的数据（0~1）
  const radar = [];
  for (let i = 0; i < fused.length; i++) {
    radar.push({ label: fused[i].name, value: fused[i].rate, pct: fused[i].pct, key: fused[i].level.key });
  }

  return {
    dims: fused,
    radar: radar,
    baseDims: base,
    probePlan: plan,
    probeGroups: probeGroups,
    probed: probeCards.length > 0,
    mastery: mastery,
    masteryText: mastery + '%',
    right: right,
    total: total,
    weak: firstWeak
      ? {
          k: firstWeak.k,
          name: dimsUtil.labelOf(subject, grade, firstWeak.k),
          pct: firstWeak.pct,
          level: firstWeak.level,
          verdict: firstWeak.verdict
        }
      : null,
    gaps: gaps,
    slips: slips,
    plan: trail,
    words: words
  };
}

