  /* 按住充能 —— 2 秒，中途松手回落 */
  function bindPalm() {
    var palm = $('#palm');
    if (!palm) return;
    var sip = $('#sip');
    var hint = $('#hint');
    var charge = 0, timer = null, decay = null;

    function stop() {
      if (timer) { clearInterval(timer); timer = null; }
      if (decay) { clearInterval(decay); decay = null; }
    }

    function down() {
      if (S.charging) return;
      S.charging = true;
      stop();
      palm.classList.add('pressing');
      hint.textContent = '灵力汇聚中…';
      charge = 0;
      timer = setInterval(function () {
        charge += 4;
        if (charge >= 100) {
          charge = 100;
          sip.style.width = '100%';
          stop();
          S.charging = false;
          palm.classList.remove('pressing');
          hint.textContent = '灵根已现';
          setTimeout(startQuiz, 320);
          return;
        }
        sip.style.width = charge + '%';
      }, 40);
    }

    function up2() {
      if (!S.charging) return;
      S.charging = false;
      stop();
      palm.classList.remove('pressing');
      hint.textContent = '还差一点 · 按住别松';
      decay = setInterval(function () {
        charge -= 9;
        if (charge <= 0) {
          charge = 0;
          sip.style.width = '0%';
          clearInterval(decay); decay = null;
          hint.textContent = '按住碑面 · 灵力自显';
          return;
        }
        sip.style.width = charge + '%';
      }, 26);
    }

    palm.addEventListener('mousedown', down);
    palm.addEventListener('touchstart', function (e) { e.preventDefault(); down(); });
    document.addEventListener('mouseup', up2);
    palm.addEventListener('touchend', up2);
    palm.addEventListener('touchcancel', up2);
  }

