  function pick(i) {
    if (pickLock) return;
    var card = curCard();
    if (!card) return;
    pickLock = true;

    var ok = i === card.a;
    var marks = curMarks();
    marks.push(ok);

    var opts = $('#opts');
    var all = opts.querySelectorAll('.opt');
    for (var k = 0; k < all.length; k++) {
      var idx = Number(all[k].getAttribute('data-i'));
      if (idx === card.a) all[k].classList.add('right');
      else if (idx === i) all[k].classList.add('wrong');
    }

    var btn = $('#nextBtn');
    btn.classList.add('on');
    btn.textContent = '下 一 问';

    var tip = $('#quizTip');
    if (tip) tip.classList.add('hide');

    var bar = $('#p-quiz .prog-bar');
    var total = S.phase === 'base' ? S.paper.length : S.probeCards.length;
    if (bar) bar.style.width = Math.round((marks.length / total) * 100) + '%';

    var br = $('#p-quiz .bar-right');
    if (br) br.textContent = rightCount() + ' 中';

    if (ok) {
      autoTimer = setTimeout(function () { autoTimer = null; pickLock = false; next(); }, 620);
      return;
    }

    var ex = $('#explain');
    ex.classList.remove('hide');
    var left = 3;
    $('#expCd').textContent = left + ' 秒后下一问';
    cdTimer = setInterval(function () {
      left -= 1;
      if (left <= 0) {
        clearInterval(cdTimer); cdTimer = null;
        pickLock = false;
        next();
        return;
      }
      $('#expCd').textContent = left + ' 秒后下一问';
      $('#expBar').style.width = (left / 3) * 100 + '%';
    }, 1000);
  }

  function next() {
    clearTimers();
    if (S.phase === 'base') {
      if (S.qi < S.paper.length - 1) { S.qi++; renderQuiz(); return; }
      // 定基结束
      S.baseDims = Diag.scoreBase(S.paper, S.marks, S.subject);
      S.plan = Diag.probePlan(S.baseDims);
      if (!S.plan.length) { finish(); return; }
      buildProbe();
      go('bridge');
      return;
    }
    if (S.pi < S.probeCards.length - 1) { S.pi++; renderQuiz(); return; }
    finish();
  }

  function buildProbe() {
    var used = S.paper.map(function (c) { return c.id; });
    var cards = [];
    for (var i = 0; i < S.plan.length; i++) {
      var p = S.plan[i];
      var got = Bank.buildProbe(S.subject, S.grade, p.k, p.size, used);
      for (var k = 0; k < got.length; k++) {
        used.push(got[k].id);
        cards.push(shuffleQ(got[k]));
      }
    }
    S.probeCards = cards;
    S.probeMarks = [];
    S.pi = 0;
  }

