/* ---------- 迷你模块系统（CommonJS 子集） ---------- */
var __mods = {}, __cache = {};
function __def(name, fn) { __mods[name] = fn; }
function __req(name) {
  if (__cache[name]) return __cache[name].exports;
  if (!__mods[name]) throw new Error('模块缺失: ' + name);
  var m = { exports: {} };
  __cache[name] = m;
  __mods[name](m, m.exports, __req);
  return m.exports;
}

