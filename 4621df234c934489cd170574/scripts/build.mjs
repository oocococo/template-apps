import {readFile, mkdir, copyFile, rm} from 'node:fs/promises';
import {build} from 'esbuild';
const commit = process.argv[2];
if (!/^[a-f0-9]{40,64}$/.test(commit || '')) throw Error('需要完整源码提交号');
const source = JSON.parse(await readFile('source.json','utf8'));
if (process.env.TIANA_TEMPLATE_BUILD !== '1' && (!source.git_instance_id || source.git_instance_id.startsWith('__TIANA_'))) throw Error('请填写 Git 实例 ID');
if (process.env.TIANA_TEMPLATE_BUILD !== '1' && (!source.database_instance_id || source.database_instance_id.startsWith('__TIANA_'))) throw Error('请填写 SQLite 实例 ID');
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await build({entryPoints:['src/app.js'],bundle:true,format:'iife',platform:'browser',outfile:'dist/assets/app.js'}); await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source}));
