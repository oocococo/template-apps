import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, readdir, rm } from 'node:fs/promises';
const commit = process.argv[2];
if (!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(commit || '')) throw new Error('请传入已核实的完整源码提交号。');
const metadata = JSON.parse(await readFile('metadata.json', 'utf8'));
const repository = metadata.source?.repository || 'https://github.com/tianacloud/template-apps';
const templateSourceURL = /^[a-f0-9]{40,64}$/.test(metadata.source?.commit || '') ? `${repository}/tree/${metadata.source.commit}/opengym` : repository;
const source = JSON.parse(await readFile('source.json', 'utf8'));
if (!process.env.TIANA_TEMPLATE_BUILD && Object.values(source).some(v => v.startsWith('__TIANA_'))) throw new Error('请先填写本次应用的 SQLite 和 Git 绑定。');
await mkdir('dist', {recursive:true});
for (const f of await readdir('dist')) await rm(`dist/${f}`, {recursive:true,force:true});
await build({entryPoints:['src/main.jsx'],bundle:true,minify:true,format:'esm',target:'es2022',outfile:'dist/assets/app.js',loader:{'.css':'text','.md':'text','.txt':'text'},define:{'process.env.NODE_ENV':'"production"','process.env.TIANA_DEMO':'"false"','process.env.TIANA_TEMPLATE_SOURCE_URL':JSON.stringify(templateSourceURL)},legalComments:'none'});
await copyFile('public/icon.png','dist/icon.png');
console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...source,source_commit:commit}));
