import {readFileSync,writeFileSync,mkdirSync,cpSync,rmSync} from 'node:fs';
import {build} from 'esbuild';
const read=p=>readFileSync(p,'utf8');
rmSync('dist',{recursive:true,force:true}); mkdirSync('dist/assets',{recursive:true});
const body=read('src/body.html'), css=read('src/assets/css/style.css');
const scripts=['icons','data-veg-fruit','data-animal','data-special','app'].map(n=>read(`src/assets/js/${n}.js`)).join('\n;\n');
const entry=`import './src/store.js';\ndocument.head.insertAdjacentHTML('beforeend',${JSON.stringify('<style>'+css+'</style>')});document.getElementById('app').innerHTML=${JSON.stringify(body)};\n${scripts}`;
await build({stdin:{contents:entry,resolveDir:process.cwd(),sourcefile:'entry.js'},outfile:'dist/assets/app.js',bundle:true,format:'esm'});
cpSync('public/icon.png','dist/icon.png'); cpSync('THIRD_PARTY_NOTICES','dist/THIRD_PARTY_NOTICES.txt');
const config=JSON.parse(read('source.json')); console.log('TIANA_PROJECT_PARAMS '+JSON.stringify({entry:'assets/app.js',...config}));
