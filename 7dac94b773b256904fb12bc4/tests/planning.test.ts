function setup(deadline = '2026-10-22', minutes = 100) {
  const s = emptyWorkspace();
  const project: Project = {id:'p1',name:'写作计划',color:'#6989b8',createdDate:'2026-10-20',startDate:'2026-10-20',deadline,bufferDays:0};
  s.projects.push(project);
  s.modules.push({id:'m1',projectId:'p1',name:'第一部分'});
  const task: Task = {id:'t1',projectId:'p1',moduleId:'m1',title:'整理材料',minutes,notes:''};
  s.tasks.push(task);
  return {s,project,task};
}
test('exact daily allocation, positive freeze, new project and actual effort remain distinct', () => {
  const {s} = setup();
  assert.equal(plan(s,'2026-10-20').total['2026-10-20'],40);
  assert.equal(Object.values(plan(s,'2026-10-20').total).reduce((a,b)=>a+b),100);
  freezeToday(s,'2026-10-20');
  s.settings.overrides['2026-10-20'] = 0;
  freezeToday(s,'2026-10-20');
  assert.equal(daySummary(s,'2026-10-20','2026-10-20').target,40);
  delete s.settings.overrides['2026-10-20'];
  s.projects.push({...s.projects[0],id:'p2',deadline:'2026-10-21'});
  s.modules.push({id:'m2',projectId:'p2',name:'模块'});
  s.tasks.push({...s.tasks[0],id:'t2',projectId:'p2',moduleId:'m2'});
  freezeToday(s,'2026-10-20');
  assert.equal(daySummary(s,'2026-10-20','2026-10-20').target,95);
  const e = scheduleTask(s,'t1','2026-10-20')!;
  complete(s,e.id,125,false,'2026-10-20');
  const summary = daySummary(s,'2026-10-20','2026-10-20');
  assert.deepEqual([summary.target,summary.planned,summary.actual,summary.invested],[95,100,125,125]);
  assert.equal(projectWork(s,'p1').remaining,0);
  freezeToday(s,'2026-10-21');
  assert.equal(daySummary(s,'2026-10-21','2026-10-21').target,100);
  assert.equal(daySummary(s,'2026-10-20','2026-10-21').target,95);
});
test('business boundaries, holidays, temporary future targets, buffer and overdue', () => {
  const {s,project} = setup('2026-10-21',60);
  project.startDate = '2026-10-19'; project.bufferDays = 1;
  const clock = Date.parse('2026-10-20T12:30:00Z');
  assert.equal(businessDay({...s.settings,timeZone:'Pacific/Kiritimati',startHour:0},clock),'2026-10-21');
  assert.equal(businessDay({...s.settings,timeZone:'America/Los_Angeles',startHour:7},clock),'2026-10-19');
  assert.equal(plan(s,'2026-10-21').projects[0].status,'buffer');
  assert.equal(plan(s,'2026-10-21').total['2026-10-21'],60);
  assert.equal(plan(s,'2026-10-22').projects[0].status,'overdue');
  assert.equal(plan(s,'2026-10-22').projects[0].unallocated,60);
  goals(s,'2026-10-21','2026-10-20');
  assert.deepEqual(s.targets,{});
  assert.equal(capacity('2026-02-17',s.settings),0);
  s.settings.overrides['2026-02-17'] = 90;
  assert.equal(capacity('2026-02-17',s.settings),90);
});
test('partial completion preserves remaining workload and undo does not double-schedule', () => {
  const {s} = setup('2026-10-25',100);
  const e = scheduleTask(s,'t1','2026-10-20')!;
  const preview = partialSuggestion(s,e.id,40,'2026-10-20');
  partialComplete(s,e.id,40,50,false,'2026-10-21',preview.fingerprint,'2026-10-20');
  assert.equal(projectWork(s,'p1').remaining,60);
  assert.equal(daySummary(s,'2026-10-20','2026-10-20').actual,50);
  assert.equal(s.entries.find(e => !e.done)?.minutes,60);
  validate(s);
  undoComplete(s,e.id);
  assert.equal(s.entries.length,1);
  assert.equal(s.entries[0].minutes,100);
  assert.equal(projectWork(s,'p1').remaining,100);
  validate(s);
});
test('calibration requires two samples and applies only to unstarted work; same signature is remembered', () => {
  const {s,task} = setup('2026-10-30',60);
  for (let i=2;i<=4;i++) s.tasks.push({...task,id:`t${i}`});
  for (let i=1;i<=2;i++) complete(s,scheduleTask(s,`t${i}`,'2026-10-20')!.id,90,false,'2026-10-20');
  const proposal = calibration(s,'m1')!;
  assert.deepEqual([proposal.sampleCount,proposal.previous,proposal.suggested],[2,120,180]);
  const kept = structuredClone(s);
  applyCalibration(kept,proposal,false);
  assert.equal(calibration(kept,'m1'),null);
  freezeToday(s,'2026-10-20');
  const frozen = structuredClone(s.targets);
  applyCalibration(s,proposal,true);
  assert.deepEqual(s.tasks.map(t => t.minutes),[60,60,90,90]);
  assert.deepEqual(s.completions.map(c => c.planned),[60,60]);
  assert.deepEqual(s.targets,frozen);
  complete(s,scheduleTask(s,'t3','2026-10-20')!.id,90,false,'2026-10-20');
  const predicted = prediction(s,s.projects[0],'2026-10-20');
  assert.equal(predicted.status,'estimated');
  assert.equal(predicted.date,'2026-10-21');
  assert.equal(predicted.adjustedRemaining,90);
});
test('replan is read-only until confirmation, respects deadlines, allows warnings, rejects changed conditions', () => {
  const {s,project} = setup('2026-10-21',60);
  project.bufferDays = 1;
  scheduleTask(s,'t1','2026-10-19');
  const before = structuredClone(s);
  const p = previewReplan(s,'2026-10-21');
  assert.deepEqual(s,before);
  assert.equal(p.changes[0].date,'2026-10-21');
  assert.ok(p.warnings.some(w => w.includes('缓冲')));
  const edited = editPreview(s,p,p.changes[0].id,'2026-10-23');
  assert.ok(edited.warnings.some(w => w.includes('截止')));
  const conflict = structuredClone(s);
  conflict.settings.weekly[1] = 15;
  assert.throws(()=>applyReplan(conflict,p),/变化/);
  applyReplan(s,p);
  assert.equal(s.entries[0].date,'2026-10-21');
  assert.equal(project.deadline,'2026-10-21');
  s.settings.weekly.fill(0);
  const empty = previewReplan(s,'2026-10-22');
  assert.equal(empty.changes.length,0);
  assert.equal(empty.unscheduled.length,1);
});
test('long-term scheduled work, ordinary linked work, and independent work have different safety contributions', () => {
  const {s,project} = setup();
  project.deadline = null;
  scheduleTask(s,'t1','2026-10-20');
  s.entries.push(makeEntry({title:'散步',minutes:30,date:'2026-10-20'}));
  freezeToday(s,'2026-10-20');
  assert.equal(daySummary(s,'2026-10-20','2026-10-20').target,100);
  complete(s,s.entries[1].id,30,false);
  assert.equal(daySummary(s,'2026-10-20','2026-10-20').invested,0);
  assert.equal(prediction(s,project,'2026-10-20').status,'longterm');
});
