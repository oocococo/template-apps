test('CSV protects spreadsheet formulas and ICS folds UTF-8 safely with exclusive end dates', () => {
  const s: Workspace = emptyWorkspace();
  s.entries.push(makeEntry({id:'fixed-id',title:'=2+2',minutes:30,date:'2026-10-20',notes:'逗号,换行\\n第二行'}));
  assert.ok(exportCsv(s,'2026-10-20','2026-10-20').includes("\"'=2+2\""));
  s.entries[0].title = '学习中文'.repeat(40);
  const ics = exportIcs(s,'2026-10-20','2026-10-20');
  assert.ok(ics.includes('DTEND;VALUE=DATE:20261021'));
  assert.ok(ics.includes('UID:fixed-id@riji'));
  assert.ok(ics.split('\r\n').every(l => new TextEncoder().encode(l).length <= 75));
  assert.equal(planningFingerprint(s),planningFingerprint(structuredClone(s)));
});
